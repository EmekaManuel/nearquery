"""Generate LIBRARIES.md: direct dependencies with pinned versions and licenses, read from the lockfiles' installs.

  python -m pipeline.libraries     (run `make setup` and `npm ci` in dashboard/ first so licenses can be read)
"""
import json
import tomllib
from importlib import metadata

from pipeline import config

ROOT = config.ROOT


def py_license(name: str) -> str:
    md = metadata.metadata(name)
    if md.get("License-Expression"):
        return md["License-Expression"]
    cls = [c.split("::")[-1].strip() for c in md.get_all("Classifier") or [] if c.startswith("License ::")]
    if cls:
        return ", ".join(cls)
    lic = (md.get("License") or "unknown").splitlines()[0]
    return lic[:60]


def main() -> None:
    py = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]["dependencies"]
    rows = []
    for dep in py:
        name, ver = dep.split("==")
        rows.append((name, ver, py_license(name), "Python"))
    pkg = json.loads((ROOT / "dashboard" / "package.json").read_text())
    for group in ("dependencies", "devDependencies"):
        for name, ver in pkg[group].items():
            lic = json.loads((ROOT / "dashboard" / "node_modules" / name / "package.json").read_text()).get("license", "unknown")
            rows.append((name, ver, lic, "Node" + (" (dev)" if group == "devDependencies" else "")))
    out = ["# Libraries, services and tools", "",
           "Generated by `python -m pipeline.libraries` from `pyproject.toml`, `uv.lock` and `dashboard/package.json`. Versions are pinned; transitive dependencies are in the lockfiles.", "",
           "## Direct dependencies", "", "| Package | Version | License | Ecosystem |", "| --- | --- | --- | --- |"]
    out += [f"| {n} | {v} | {l} | {e} |" for n, v, l, e in rows]
    out += ["", "## Fonts (Google Fonts, loaded at build by `next/font`)", "",
            "Space Grotesk, IBM Plex Sans, IBM Plex Mono: SIL Open Font License 1.1.", "",
            "## Data sources and services", "",
            "| Source | Used for | Terms note |", "| --- | --- | --- |",
            "| BigQuery public dataset `bigquery-public-data.crypto_near_mainnet_us` | On-chain `intents.near` event logs (raw pull is optional) | No restriction on derived results found; Google public-dataset terms apply. |",
            "| DefiLlama API (`api.llama.fi`, `coins.llama.fi`) | Prices, reported volume, fees, revenue | ToS 8(7) forbids republishing their data; raw series are re-fetched at build, never committed or displayed. |",
            "| FastNEAR free RPC | Token metadata, NEAR total supply | Free, keyless. |",
            "| Dune public dashboard | Spot cross-checks transcribed on 2026-10-30; not used in any computed number | Read by eye; no API used. |",
            "", "## Excluded on purpose", "", "NEAR Explorer API (terms §4.1(e)); see METHODOLOGY.md.", "",
            "## AI assistance", "", "Most of the code, SQL and prose in this repository was written with Claude Code (Anthropic) and reviewed by the author. See README.md.", ""]
    (ROOT / "LIBRARIES.md").write_text("\n".join(out))
    print(f"wrote LIBRARIES.md ({len(rows)} direct dependencies)")


if __name__ == "__main__":
    main()
