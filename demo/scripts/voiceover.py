"""Write submission/VOICEOVER.md: a timed read-aloud script for the demo video.

  python demo/scripts/voiceover.py

Numbers and dates come from demo/out/numbers.json (pipeline output), spoken out in words. Shot lengths mirror SHOTS in
demo/src/captions.ts; keep them in step if that changes.
"""
import datetime as dt
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
N = json.loads((ROOT / "demo" / "out" / "numbers.json").read_text())
SHOTS = [("Hook", 8), ("Method", 10), ("The moment", 18), ("The surprise", 22), ("Falsifiers", 12), ("Re-run", 10), ("Outro", 8)]
WPS = 2.3  # comfortable speaking pace, words per second


def ordinal(d: int) -> str:
    return f"{d}{'th' if 11 <= d % 100 <= 13 else {1: 'st', 2: 'nd', 3: 'rd'}.get(d % 10, 'th')}"


def day(iso: str) -> str:
    d = dt.date.fromisoformat(iso)
    return f"{d.strftime('%B')} {ordinal(d.day)}"


def money(s: str) -> str:
    m = re.fullmatch(r"\$([\d.]+)([BMK]?)", s)
    num, unit = m.groups()
    num = num.rstrip("0").rstrip(".") if "." in num else num
    return f"{num} {({'B': 'billion', 'M': 'million', 'K': 'thousand'}[unit] + ' ') if unit else ''}dollars"


pct = lambda s: s.replace("%", " percent")
times = lambda s: s.replace("\u00d7", " times")
LINES = [
    f"NEAR Intents settled {money(N['net_swap'])} in thirty days. Does any of it reach the NEAR token?",
    "We read the chain: every swap, straight from the event logs. Every chart is one click from its query.",
    f"Captured revenue is {money(N['revenue_year'])} a year: {pct(N['buyback_yield'])} of NEAR's market cap. Now stress-test it. Drag the volume up. "
    f"It takes {times(N['need_vol_trigger'])} today's volume to reach {pct(N['t_yield'])}. Real infrastructure, thin value for the token.",
    f"About {pct(N['confidential'])} of reported volume isn't in public events. The obvious story: Confidential Intents. "
    f"But it sits near zero until {day(N['break_date'])}, then jumps to {pct(N['conf_after'])}, while public volume doesn't rise with it. "
    "Users moving, or a data change? We can't tell, so we say so.",
    f"We also say what would change our mind: four triggers, each with today's reading. Today, {N['triggers_today']} has triggered.",
    "One command re-runs it all. No accounts, no keys. The thesis comes out identical.",
    "NearQuery. Ask the chain. Show the work. What would change your mind?",
]
assert len(LINES) == len(SHOTS)
rows, t = [], 0
for (name, secs), text in zip(SHOTS, LINES):
    w = len(text.split())
    rows.append((t, t + secs, name, secs, w, w / WPS, text))
    t += secs
mmss = lambda s: f"{s // 60}:{s % 60:02d}"
out = ["# Voiceover script (read aloud; generated by demo/scripts/voiceover.py)", "",
       f"Total video length {mmss(t)}. Numbers are spoken from `demo/out/numbers.json`, so they match the screen. Rebuild the video (`make video`) and rerun the generator if the numbers change.", "",
       "| Time | Shot | Fits? | Read this |", "| --- | --- | --- | --- |"]
for a, b, name, secs, w, est, text in rows:
    out.append(f"| {mmss(a)} to {mmss(b)} | {name} ({secs} s) | about {est:.0f} s of speech, {'ok' if est <= secs - 0.5 else 'TIGHT'} | {text} |")
out += ["", "## How to record", "",
        "- Start each line when its shot starts (the Time column); finish a beat before the next shot. A short pause is fine: the picture holds on the chart.",
        "- Say the numbers slowly; they are on screen for the whole shot. Do not speed up to fit.",
        "- Dots in \"intents dot near\" are spoken, not written. \"NEAR\" is one word.",
        "- Record each shot as its own take, so a slip means redoing eight seconds, not the whole video.",
        "- The terminal clip is sped up (the badge says so); talk at your normal pace over it.",
        "- Quiet room, mic about a hand's width from your mouth, soft furnishings nearby. Do a test take and listen with headphones.",
        "", "## Add it to the video", "",
        "With iMovie: import the video and your takes, drop each take at its start time, export 1080p. Or with ffmpeg, from one file `voice.wav` made the length of the video:", "",
        "```", "ffmpeg -i demo/out/nearquery-demo-nocaptions.mp4 -i voice.wav -map 0:v -map 1:a -c:v copy -c:a aac -b:a 192k -shortest demo/out/nearquery-demo-voice.mp4", "```"]
(ROOT / "submission" / "VOICEOVER.md").write_text("\n".join(out) + "\n")
print("\n".join(out[4 : 6 + len(rows)]))
