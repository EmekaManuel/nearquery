"""Write submission/VOICEOVER.md: a timed read-aloud script for the demo video.

  python demo/scripts/voiceover.py

Numbers and dates come from demo/out/numbers.json (pipeline output), spoken out in words. Shot lengths mirror SHOTS in
demo/src/captions.ts; keep them in step if that changes.
"""
import datetime as dt
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
N = json.loads((ROOT / "demo" / "out" / "numbers.json").read_text())
SHOTS = [("Hook", 8), ("Method", 10), ("The moment", 18), ("The surprise", 22), ("Checks", 14), ("Falsifiers", 12), ("Re-run", 16), ("Outro", 8)]
WPS = 2.3  # comfortable speaking pace, words per second


def ordinal(d: int) -> str:
    return f"{d}{'th' if 11 <= d % 100 <= 13 else {1: 'st', 2: 'nd', 3: 'rd'}.get(d % 10, 'th')}"


def day(iso: str) -> str:
    d = dt.date.fromisoformat(iso)
    return f"{d.strftime('%B')} {ordinal(d.day)}"


def money(s: str) -> str:
    m = re.fullmatch(r"\$([\d.]+)([BMK]?)", s)
    num, unit = m.groups()
    num = num.rstrip("0").rstrip(".") if "." in num else num
    return f"{num} {({'B': 'billion', 'M': 'million', 'K': 'thousand'}[unit] + ' ') if unit else ''}dollars"


pct = lambda s: s.replace("%", " percent")
times = lambda s: s.replace("\u00d7", " times")
# (shot, start second on the final timeline, end second, what is on screen at that moment, line to read)
H, M, O, S, C, F, R, X = 0, 8, 18, 36, 58, 72, 84, 100
CUES = [
    ("Hook", H + 0.2, H + 3.95, "the counter rolls up to the figure", f"Intents settled {money(N['net_swap'])} in thirty days."),
    ("Hook", H + 4.0, H + 7.8, "the question rises", "Does any of it reach the NEAR token?"),
    ("Method", M + 0.2, M + 4.7, "the volume chart, cursor sweeping, Source callout", "We read the chain: every swap, from the event logs."),
    ("Method", M + 4.8, M + 9.8, "click Open, the query block, Copy", "Every chart is one click from the query behind it."),
    ("The moment", O + 0.2, O + 5.9, "value page, slider at 1x", f"Captured revenue: {money(N['revenue_year'])} a year, {pct(N['buyback_yield'])} of market cap."),
    ("The moment", O + 6.0, O + 10.8, "the slider is dragged to the right", "Now stress-test it. Drag the volume up."),
    ("The moment", O + 11.0, O + 17.8, "callout: 2% of market cap = 4.7x volume", f"It takes {times(N['need_vol_trigger'])} today's volume to reach {pct(N['t_yield'])}: real infrastructure, thin token value."),
    ("The surprise", S + 0.2, S + 5.8, "implied confidential chart, flat line", f"About {pct(N['confidential'])} of volume isn't public. The obvious story: Confidential Intents."),
    ("The surprise", S + 5.9, S + 13.8, "zoom and ring land on the step", f"But it sits near zero until {day(N['break_date'])}, then jumps to {pct(N['conf_after'])}. Public volume doesn't rise."),
    ("The surprise", S + 14.2, S + 21.8, "scroll to the caveats card", "Users moving, or a data change? We can't tell, so we say so."),
    ("Checks", C + 0.2, C + 6.6, "the wash and bot chart, then a callout", f"A wash and bot screen sets aside only {N['wash_total'].replace('%', ' percent')} of user volume."),
    ("Checks", C + 7.0, C + 13.8, "the peer fee bars, NEAR Intents highlighted", f"And NEAR Intents' fees, {N['near_fee_1m'].replace('$', '').replace(',', '')} dollars per million, rank {N['near_fee_rank_ord']} of {N['n_peers']} cross-chain protocols."),
    ("Falsifiers", F + 0.2, F + 6.0, "the table draws row by row", "We say what would change our mind: four triggers, with today's readings."),
    ("Falsifiers", F + 6.2, F + 11.6, "the closing line fades in", f"Today, {N['triggers_today']} has triggered."),
    ("Re-run", R + 0.2, R + 4.5, "the command is typed", "One command re-runs it all. No accounts, no keys."),
    ("Re-run", R + 4.6, R + 9.6, "the terminal scrolls (sped up)", "It refetches market data, rebuilds every metric, then rewrites the thesis."),
    ("Re-run", R + 9.8, R + 15.2, "result line: THESIS.md: no changes", "Same inputs, same output. The thesis comes out identical."),
    ("Outro", X + 0.4, X + 3.8, "logo and tagline", "NearQuery. Ask the chain. Show the work."),
    ("Outro", X + 3.9, X + 7.6, "the question, then the repo address", "What would change your mind?"),
]
rows = []
for name, a, b, shows, text in CUES:
    w = len(text.split())
    rows.append((a, b, name, shows, w, w / WPS, text))
t = sum(x for _, x in SHOTS)
mmss = lambda s: f"{int(s) // 60}:{s % 60:04.1f}"
out = ["# Voiceover script (read aloud; generated by demo/scripts/voiceover.py)", "",
       f"Total video length {mmss(t)}. Numbers are spoken from `demo/out/numbers.json`, so they match the screen. Rebuild the video (`make video`) and rerun the generator if the numbers change.", "",
       "| Start to end | Shot | On screen | Fits? | Read this |", "| --- | --- | --- | --- | --- |"]
for a, b, name, shows, w, est, text in rows:
    out.append(f"| {mmss(a)} to {mmss(b)} | {name} | {shows} | {w} words, {est:.1f} s of {b - a:.1f} s: {'ok' if est <= b - a else 'TIGHT'} | {text} |")
out += ["", "## How to record", "",
        "- Start each line at its start time and finish by its end time; the On screen column says what the picture is doing. Silence between lines is intended. A short pause is fine: the picture holds on the chart.",
        "- Say the numbers slowly; they are on screen for the whole shot. Do not speed up to fit.",
        "- Dots in \"intents dot near\" are spoken, not written. \"NEAR\" is one word.",
        "- Record each line as its own take, so a slip means redoing a few seconds, not the whole video.",
        "- The terminal clip is sped up about 2x (the badge says so); talk at your normal pace over it.",
        "- Quiet room, mic about a hand's width from your mouth, soft furnishings nearby. Do a test take and listen with headphones.",
        "", "## Add it to the video", "",
        "With iMovie: import the video and your takes, drop each take at its start time, export 1080p. Or with ffmpeg, from one file `voice.wav` made the length of the video:", "",
        "```", "ffmpeg -i demo/out/nearquery-demo-nocaptions.mp4 -i voice.wav -map 0:v -map 1:a -c:v copy -c:a aac -b:a 192k -shortest demo/out/nearquery-demo-voice.mp4", "```"]
(ROOT / "submission" / "VOICEOVER.md").write_text("\n".join(out) + "\n")
print("\n".join(out[4 : 6 + len(rows)]))
